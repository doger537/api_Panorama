"""Generate transport DTOs from the repository's deliberately small OpenAPI subset."""
import json
from pathlib import Path
import sys
import yaml
ROOT = Path(__file__).resolve().parents[1]


def typescript(schema):
    nullable = schema.get('nullable', False)
    if '$ref' in schema:
        result = schema['$ref'].split('/')[-1]
    elif 'allOf' in schema:
        result = ' & '.join(typescript(s) for s in schema['allOf'])
    elif 'enum' in schema:
        result = ' | '.join(json.dumps(v, ensure_ascii=False) for v in schema['enum'])
    elif schema.get('type') == 'array':
        result = f"Array<{typescript(schema['items'])}>"
    elif schema.get('type') == 'object' or 'properties' in schema:
        required = schema.get('required', [])
        result = '{ ' + '; '.join(f"{key}{'' if key in required else '?'}: {typescript(value)}" for key, value in schema.get('properties', {}).items()) + ' }'
    else:
        result = {'integer': 'number', 'number': 'number', 'string': 'string', 'boolean': 'boolean'}.get(schema.get('type'), 'unknown')
        if schema.get('format') == 'binary': result = 'File'
    return f'({result}) | null' if nullable else result


def generate():
    schemas = yaml.safe_load((ROOT / 'CONTRACTS/openapi.yaml').read_text())['components']['schemas']
    lines = ['/** Generated by scripts/generate_types.py; edit CONTRACTS/openapi.yaml. */']
    for name, schema in schemas.items(): lines.append(f'export type {name} = {typescript(schema)};')
    # Named aliases for inline contract enums, kept for consumer readability.
    for alias, owner, field in [('ErrorCode','ApiError','error'), ('CaptureState','Capture','state'), ('JobError','Capture','error_code')]:
        if alias == 'ErrorCode': lines.append("export type ErrorCode = ApiError['error']['code'];")
        else: lines.append(f"export type {alias} = NonNullable<{owner}['{field}']>;")
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    expected=generate(); path=ROOT/'CONTRACTS/types.ts'
    if '--check' in sys.argv:
        if path.read_text()!=expected: raise SystemExit('DTO drift: run python scripts/generate_types.py')
    else: path.write_text(expected)
